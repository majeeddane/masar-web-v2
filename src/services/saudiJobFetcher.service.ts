export class SaudiJobService {
    // إدراج وتنظيم كافة الوظائف السعودية في قاعدة البيانات
    async seedSaudiJobs(): Promise<{ inserted: number; updated: number; message: string }> {
        const supabase = getAdminSupabase();

        // 1. جلب معرف حساب المشرف لربط الوظائف به
        let defaultUserId: string = 'cf649393-bdd3-49e0-b1ca-e83452ce92fa';
        try {
            const { data: adminUser } = await supabase.from('profiles').select('id').eq('is_admin', true).limit(1).maybeSingle();
            if (adminUser?.id) defaultUserId = adminUser.id;
        } catch (e) {
            console.warn('Using default admin id');
        }

        let insertedCount = 0;

        for (const job of SAUDI_REAL_JOBS) {
            try {
                // فحص إذا كانت الوظيفة موجودة مسبقاً بنفس العنوان والشركة والمدينة
                const { data: existing } = await supabase
                    .from('jobs')
                    .select('id')
                    .eq('title', job.title)
                    .eq('company_name', job.company_name)
                    .eq('city', job.city)
                    .maybeSingle();

                const payload = {
                    user_id: defaultUserId,
                    title: job.title,
                    company_name: job.company_name,
                    category: job.category,
                    city: job.city,
                    location: job.location,
                    type: job.job_type,
                    job_type: job.job_type,
                    experience_level: job.experience_level,
                    salary_range: job.salary_range,
                    description: job.description,
                    phone: job.phone,
                    phone_number: job.phone,
                    contact_phone: job.phone,
                    email: job.email,
                    contact_email: job.email,
                    application_link: job.application_link,
                    is_active: true
                };

                if (existing?.id) {
                    await supabase.from('jobs').update(payload).eq('id', existing.id);
                } else {
                    const { error } = await supabase.from('jobs').insert(payload);
                    if (!error) insertedCount++;
                }
            } catch (err: any) {
                console.error(`Error inserting Saudi job (${job.title}):`, err?.message || err);
            }
        }

        return {
            inserted: insertedCount,
            updated: SAUDI_REAL_JOBS.length - insertedCount,
            message: `تم تنظيم وتثبيت ${SAUDI_REAL_JOBS.length} وظيفة حقيقية معتمدة موزعة على جميع المدن والأقسام السعودية!`
        };
    }
}

export const saudiJobService = new SaudiJobService();
